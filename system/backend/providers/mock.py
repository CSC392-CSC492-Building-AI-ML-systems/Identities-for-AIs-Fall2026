"""Deterministic offline target for backend development.

This provider does not load credentials, reach the network, retain prompts, or
pretend to be an actual LLM. All responses are synthetic. The real provider
integration will replace this behind CallableTargetClient.
"""
from __future__ import annotations


class MockTargetProvider:
    def send_prompt(self, prompt_text: str) -> str:
        if not isinstance(prompt_text, str) or not prompt_text.strip():
            raise ValueError("A prompt is required")
        return "Synthetic development-only response. Not generated by a real language model."
