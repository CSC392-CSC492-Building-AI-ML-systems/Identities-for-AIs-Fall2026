#!/usr/bin/env python3
"""Aggregate existing one-vs-rest validation outputs into model-confusion reports.

Requires *no retraining*. Works with results generated by train_baselines.py.
Reads only saved validation predictions/thresholds and (optional) original
validation_metrics.csv files, never the test set.

Outputs per-target metrics, true-negative-model rejection / false-acceptance
rates, target false alarms, and a wide model-by-model acceptance matrix.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import warnings

import numpy as np
import pandas as pd

from consolidation import safe_slug
from metrics_common import score_metrics, load_binary

ALGORITHMS = ('rf_stylometry', 'lr_tfidf')
RULES = ('fixed_0.5', 'validation_false_alarm_limit')


def discover_targets(data_root: Path) -> list[str]:
    """Get canonical model keys from the consolidation manifest, not folder guesses."""
    manifest = data_root / 'summary.json'
    if not manifest.is_file():
        raise FileNotFoundError(f'Missing {manifest}; run prepare_supervised_data.py first.')
    meta = json.loads(manifest.read_text(encoding='utf-8'))
    models = meta.get('models')
    if not isinstance(models, list) or not models or len(set(models)) != len(models):
        raise ValueError(f'Expected nonempty unique models list in {manifest}')
    return sorted(models)


def load_prediction_with_threshold(results_root: Path, target: str, view: str, algo: str) -> tuple[pd.DataFrame, float]:
    root = results_root / safe_slug(target) / view
    pred_path = root / f'{algo}_validation_predictions.csv'
    threshold_path = root / f'{algo}_threshold.json'
    if not pred_path.is_file() or not threshold_path.is_file():
        raise FileNotFoundError(f'Missing saved validation results: {pred_path} or {threshold_path}')
    pred = pd.read_csv(pred_path, keep_default_na=False, dtype={'record_id': str, 'prompt_id': str})
    threshold_info = json.loads(threshold_path.read_text(encoding='utf-8'))
    if (threshold_info.get('target_model') != target or
        threshold_info.get('algorithm') != algo or
        threshold_info.get('view') != view):
        raise ValueError(f'Threshold configuration does not match target/algo/view: {threshold_path}')
    needed = {'record_id', 'prompt_id', 'model_key', 'label', 'target_score'}
    if not needed.issubset(pred.columns):
        raise ValueError(f'{pred_path} missing {sorted(needed - set(pred.columns))}')
    if pred.empty or not pred['record_id'].is_unique:
        raise ValueError(f'Empty or duplicate record_id values in {pred_path}')
    if set(pred['label'].astype(int).unique()) != {0, 1}:
        raise ValueError(f'Both classes required in {pred_path}')
    if not (pred['label'].astype(int) == (pred['model_key'] == target).astype(int)).all():
        raise ValueError(f'Inconsistent binary labels in {pred_path}')
    pred['target_score'] = pd.to_numeric(pred['target_score'], errors='raise')
    if not np.isfinite(pred['target_score'].to_numpy()).all():
        raise ValueError(f'Nonfinite scores in {pred_path}')
    thresh = float(threshold_info['threshold'])
    if not np.isfinite(thresh):
        raise ValueError(f'Nonfinite threshold in {threshold_path}')
    return pred, thresh


def create_reports(data_root: Path, results_root: Path, out: Path, view: str = 'all_personas',
                   algorithms: tuple[str, ...] = ALGORITHMS,
                   require_all: bool = False) -> dict:
    models = discover_targets(data_root)
    out.mkdir(parents=True, exist_ok=True)
    overall, negatives, positives, all_pred, missing, run_info = [], [], [], [], [], []
    for target in models:
        expected_validation = load_binary(data_root, target, view, 'validation')
        for algo in algorithms:
            try:
                pred, selected_threshold = load_prediction_with_threshold(results_root, target, view, algo)
            except FileNotFoundError as e:
                missing.append({'target_model': target, 'algorithm': algo, 'missing': str(e)})
                continue
            # Never mix saved predictions from an older consolidation run.
            expected_ids = set(expected_validation.record_id.astype(str))
            actual_ids = set(pred.record_id.astype(str))
            if expected_ids != actual_ids:
                raise ValueError(
                    f'Stale validation predictions for {target}/{algo}: record IDs differ from the current dataset. '
                    'Retrain this target after backing up the old results.'
                )
            truth_metadata = expected_validation.set_index('record_id')[['prompt_id','model_key','label']]
            for col in ['prompt_id','model_key','label']:
                saved = pred.set_index('record_id')[col].loc[truth_metadata.index].astype(str)
                current = truth_metadata[col].astype(str)
                if not saved.equals(current):
                    raise ValueError(f'Stale/inconsistent {col} metadata in saved predictions for {target}/{algo}.')
            expected = set(models)
            present = set(pred.model_key.unique())
            if not present.issubset(expected):
                raise ValueError(f'{target}/{algo} contains unknown models: {sorted(present - expected)}')
            # Guard against mixing results from different collection versions.
            # Missing classes can indicate a partial dataset; warn instead of inventing rates.
            if present != expected:
                warnings.warn(f'{target}/{algo}: expected models {sorted(expected)}, found {sorted(present)}')
            for rule, threshold in [('fixed_0.5', 0.5), ('validation_false_alarm_limit', selected_threshold)]:
                scores = pred.target_score.to_numpy(dtype=float)
                truth = pred.label.to_numpy(dtype=int)
                guessed = (scores >= threshold).astype(int)
                metrics = score_metrics(truth, scores, threshold, 'validation', algo, target, rule)
                overall.append(metrics)
                positive = pred.loc[truth == 1]
                fp_baseline = int((guessed[truth == 1] == 0).sum())
                positives.append({
                    'target_model': target, 'algorithm': algo, 'threshold_rule': rule,
                    'threshold': threshold, 'genuine_target_n': len(positive),
                    'correctly_accepted_target': len(positive) - fp_baseline,
                    'false_alarms': fp_baseline,
                    'target_recall': (len(positive) - fp_baseline) / len(positive),
                    'false_alarm_rate': fp_baseline / len(positive),
                })
                for other_model in models:
                    if other_model == target:
                        continue
                    is_other = (pred.model_key == other_model).to_numpy()
                    other_n = int(is_other.sum())
                    if other_n == 0:
                        continue
                    false_accept_n = int((guessed[is_other] == 1).sum())
                    negatives.append({
                        'target_model': target, 'negative_model': other_model,
                        'algorithm': algo, 'threshold_rule': rule,
                        'threshold': threshold, 'n_negative_responses': other_n,
                        'correctly_rejected': other_n - false_accept_n,
                        'incorrectly_accepted': false_accept_n,
                        'change_detection_rate': (other_n - false_accept_n) / other_n,
                        'false_acceptance_rate': false_accept_n / other_n,
                    })
                slim = pred[[x for x in [
                    'record_id', 'prompt_id', 'model_key', 'prompt_category', 'persona_id',
                    'label', 'target_score'] if x in pred.columns]].copy()
                slim.insert(0, 'target_model', target)
                slim['algorithm'] = algo
                slim['threshold_rule'] = rule
                slim['threshold'] = threshold
                slim['predicted_target'] = guessed
                slim['correct'] = (guessed == truth).astype(int)
                all_pred.append(slim)
            run_info.append({'target_model': target, 'algorithm': algo, 'n': len(pred),
                             'distinct_prompts': pred.prompt_id.nunique(), 'negative_models': sorted(present - {target})})
    if missing and require_all:
        raise FileNotFoundError('Missing results for one or more expected target/algorithm combinations:\n' + '\n'.join(
            f"- {r['target_model']}/{r['algorithm']}: {r['missing']}" for r in missing
        ))
    if not overall:
        raise ValueError('No saved validation prediction files were found. Train at least one target first.')
    overall_df = pd.DataFrame(overall).sort_values(['algorithm','target_model','threshold_rule'])
    negatives_df = pd.DataFrame(negatives).sort_values(['algorithm','target_model','threshold_rule','negative_model'])
    positive_df = pd.DataFrame(positives).sort_values(['algorithm','target_model','threshold_rule'])
    combined = pd.concat(all_pred, ignore_index=True)
    matrix = negatives_df.pivot_table(
        index=['algorithm','threshold_rule','target_model'], columns='negative_model',
        values='false_acceptance_rate', aggfunc='first', dropna=False
    ).reset_index()
    matrix.columns.name = None
    order = ['algorithm', 'threshold_rule', 'target_model'] + models
    matrix = matrix.reindex(columns=order)
    overall_df.to_csv(out / 'overall_validation_metrics.csv', index=False)
    negatives_df.to_csv(out / 'negative_model_rates.csv', index=False)
    positive_df.to_csv(out / 'baseline_false_alarm_rates.csv', index=False)
    matrix.to_csv(out / 'negative_acceptance_matrix.csv', index=False)
    combined.to_csv(out / 'all_validation_predictions.csv', index=False)
    manifest = {
        'created_at_utc': datetime.now(timezone.utc).isoformat(),
        'model_keys': models, 'view': view,
        'algorithms': list(algorithms), 'threshold_rules': list(RULES),
        'completed': run_info, 'missing': missing,
        'definitions': {
            'label': '1 = target model, 0 = any other model',
            'incorrectly_accepted': 'negative-model response predicted as the target (missed change)',
            'false_acceptance_rate': 'incorrectly_accepted / n_negative_responses',
            'change_detection_rate': 'correctly_rejected / n_negative_responses',
            'false_alarm_rate': 'genuine target response predicted negative / genuine target responses',
            'threshold_rule': 'fixed_0.5, or threshold selected from positive-class validation scores',
            'matrix': 'rows = target detectors; columns = negative-model actual identities; values = false acceptance rates; empty diagonal = not applicable',
        },
        'warning': 'Validation metrics are exploratory; do not tune using the final test partition. Repeated responses to the same prompt are correlated.'
    }
    (out / 'report_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    return {'models': models, 'completed': len(run_info), 'missing': missing,
            'overall': overall_df, 'negatives': negatives_df,
            'positives': positive_df, 'out': out}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-root', type=Path, default=Path('collector/data/supervised'))
    parser.add_argument('--results-root', type=Path, default=Path('collector/data/supervised_results'))
    parser.add_argument('--out', type=Path, default=Path('collector/data/supervised_results/comparison'))
    parser.add_argument('--view', default='all_personas')
    parser.add_argument('--models', nargs='+', choices=['rf', 'lr'], default=['rf','lr'])
    parser.add_argument('--require-all', action='store_true', help='Fail if any expected results are missing')
    args = parser.parse_args()
    keys = tuple(dict.fromkeys({'rf': 'rf_stylometry', 'lr': 'lr_tfidf'}[x] for x in args.models))
    res = create_reports(args.data_root, args.results_root, args.out, args.view, keys, args.require_all)
    print(f'Aggregated {res["completed"]} model+algorithm combinations into {args.out.resolve()}')
    print('Key files: negative_model_rates.csv, negative_acceptance_matrix.csv, overall_validation_metrics.csv')
    if res['missing']:
        print('Incomplete combinations (no invented rates):')
        for r in res['missing']:
            print(f"  {r['target_model']}/{r['algorithm']}")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
